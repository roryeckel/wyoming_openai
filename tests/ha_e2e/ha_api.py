"""Home Assistant REST and websocket setup for the end-to-end harness."""

from __future__ import annotations

import json
import logging
import secrets
import time
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import httpx
from websockets.sync.client import connect as sync_connect

from .config import RESET_COMMAND, HaE2ESettings

_LOGGER = logging.getLogger(__name__)

HTTP_TIMEOUT = httpx.Timeout(60.0, connect=10.0)
READY_TIMEOUT_SECONDS = 180.0
ENTRY_TIMEOUT_SECONDS = 120.0
ENTITY_TIMEOUT_SECONDS = 90.0
ENTRY_STATE_FILENAME = "config_entries.json"
# Titles come from the proxy's Wyoming ASR/TTS program names.  They are the
# only stable identifier the config-entry API exposes; the API omits entry data,
# which contains host/port.
PROXY_ENTRY_TITLES = frozenset({"openai", "openai-streaming", "openai-realtime"})


class HaUnavailableError(RuntimeError):
    """Home Assistant did not become reachable."""


class HarnessConfigError(RuntimeError):
    """The harness cannot continue without a reset or manual fix."""


class HaApiError(RuntimeError):
    """A Home Assistant REST or websocket call failed."""


@dataclass(frozen=True)
class HarnessCredentials:
    """Test-only Home Assistant credentials generated by the harness."""

    username: str
    password: str
    client_id: str
    refresh_token: str


@dataclass(frozen=True)
class HaSession:
    """An authenticated Home Assistant session."""

    access_token: str
    credentials: HarnessCredentials


@dataclass(frozen=True)
class PipelineInfo:
    """A pipeline created by the harness."""

    id: str
    stt_entity_id: str
    tts_entity_id: str | None
    voice: str | None


@dataclass(frozen=True)
class HaStack:
    """Everything pytest needs after Home Assistant has been configured."""

    settings: HaE2ESettings
    session: HaSession
    rest: HaRestClient
    good: PipelineInfo
    bad_stt: PipelineInfo
    conversation_engine: str
    conversation_id: str
    ha_version: str


def _write_credentials(path: Path, credentials: HarnessCredentials) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "username": credentials.username,
        "password": credentials.password,
        "client_id": credentials.client_id,
        "refresh_token": credentials.refresh_token,
        "created_at": datetime.now(UTC).isoformat(),
    }
    path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    try:
        path.chmod(0o600)
    except OSError:
        pass


def _read_credentials(path: Path) -> HarnessCredentials:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
        return HarnessCredentials(
            username=payload["username"],
            password=payload["password"],
            client_id=payload["client_id"],
            refresh_token=payload["refresh_token"],
        )
    except (OSError, KeyError, TypeError, ValueError) as exc:
        raise HarnessConfigError(
            f"cannot read harness credentials from {path}: {exc}. Reset Home Assistant with: {RESET_COMMAND}"
        ) from exc


def _entry_state_path(settings: HaE2ESettings) -> Path:
    return settings.state_dir / ENTRY_STATE_FILENAME


def _load_entry_state(settings: HaE2ESettings) -> dict[str, str]:
    path = _entry_state_path(settings)
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    if not isinstance(payload, dict):
        return {}
    return {str(key): str(value) for key, value in payload.items() if isinstance(value, str)}


def _save_entry_state(settings: HaE2ESettings, state: dict[str, str]) -> None:
    path = _entry_state_path(settings)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")


def _wyoming_entry_key(settings: HaE2ESettings, host: str) -> str:
    return f"wyoming:{host}:{settings.wyoming_port}"


def _reset_untracked_wyoming_entries(
    rest: HaRestClient,
    settings: HaE2ESettings,
    state: dict[str, str],
) -> None:
    """Remove duplicate proxy entries left by older harness runs.

    The config-entry API does not expose the host/port data, so a state file is
    the harness's source of truth.  Entries whose title matches a proxy program
    but whose ID is not tracked are leftovers and would otherwise accumulate on
    every run.
    """

    tracked_ids = set(state.values())
    for entry in rest.list_config_entries("wyoming"):
        entry_id = str(entry.get("entry_id", ""))
        if entry_id in tracked_ids:
            continue
        if entry.get("title") in PROXY_ENTRY_TITLES:
            _LOGGER.info("Removing untracked Wyoming config entry %s (%s)", entry_id, entry.get("title"))
            rest.delete_config_entry(entry_id)
            time.sleep(0.2)


class HaRestClient:
    """Thin synchronous REST client."""

    def __init__(self, settings: HaE2ESettings, token: str | None = None) -> None:
        self.settings = settings
        self.token = token
        self._client = httpx.Client(base_url=settings.base_url, timeout=HTTP_TIMEOUT)

    def close(self) -> None:
        self._client.close()

    def _headers(self, *, auth: bool) -> dict[str, str]:
        if auth and self.token:
            return {"Authorization": f"Bearer {self.token}"}
        return {}

    def request(
        self,
        method: str,
        path: str,
        *,
        auth: bool = True,
        json_body: Any | None = None,
        data: dict[str, str] | None = None,
        params: dict[str, str] | None = None,
    ) -> httpx.Response:
        try:
            return self._client.request(
                method,
                path,
                headers=self._headers(auth=auth),
                json=json_body,
                data=data,
                params=params,
            )
        except httpx.HTTPError as exc:
            raise HaUnavailableError(f"Home Assistant request {method} {path} failed: {exc}") from exc

    def get_json(self, path: str, *, auth: bool = True, params: dict[str, str] | None = None) -> Any:
        response = self.request("GET", path, auth=auth, params=params)
        self._raise_for_status(response, path)
        return response.json()

    def post_json(self, path: str, body: Any | None = None, *, auth: bool = True) -> Any:
        response = self.request("POST", path, auth=auth, json_body=body)
        self._raise_for_status(response, path)
        return response.json() if response.content else None

    @staticmethod
    def _raise_for_status(response: httpx.Response, path: str) -> None:
        if response.is_success:
            return
        body = response.text[:2000]
        raise HaApiError(f"Home Assistant {path} returned HTTP {response.status_code}: {body}")

    def wait_until_up(self, timeout: float = READY_TIMEOUT_SECONDS) -> None:
        deadline = time.monotonic() + timeout
        last_error: Exception | None = None
        while time.monotonic() < deadline:
            try:
                response = self.request("GET", "/api/onboarding", auth=False)
                if response.status_code == 200:
                    return
                last_error = HaApiError(f"HTTP {response.status_code}")
            except HaUnavailableError as exc:
                last_error = exc
            time.sleep(1.0)
        raise HaUnavailableError(
            f"Home Assistant did not answer {self.settings.base_url}/api/onboarding within {timeout}s "
            f"({last_error}). Start the stack with docker-compose.ha-e2e.yml first."
        )

    def wait_running(self, timeout: float = READY_TIMEOUT_SECONDS) -> None:
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            try:
                config = self.get_json("/api/config")
                if config.get("state") == "RUNNING":
                    return
            except (HaApiError, HaUnavailableError):
                pass
            time.sleep(1.0)
        raise HaUnavailableError(f"Home Assistant did not reach RUNNING within {timeout}s")

    def onboarding_status(self) -> list[dict[str, Any]]:
        return self.get_json("/api/onboarding", auth=False)

    def create_onboarding_user(self, username: str, password: str) -> str:
        response = self.request(
            "POST",
            "/api/onboarding/users",
            auth=False,
            json_body={
                "client_id": self.settings.client_id,
                "name": "HA E2E",
                "username": username,
                "password": password,
                "language": "en",
            },
        )
        self._raise_for_status(response, "/api/onboarding/users")
        return response.json()["auth_code"]

    def exchange_code(self, code: str) -> dict[str, Any]:
        response = self.request(
            "POST",
            "/auth/token",
            auth=False,
            data={
                "client_id": self.settings.client_id,
                "grant_type": "authorization_code",
                "code": code,
            },
        )
        self._raise_for_status(response, "/auth/token")
        return response.json()

    def refresh_access_token(self, refresh_token: str) -> dict[str, Any]:
        response = self.request(
            "POST",
            "/auth/token",
            auth=False,
            data={
                "client_id": self.settings.client_id,
                "grant_type": "refresh_token",
                "refresh_token": refresh_token,
            },
        )
        self._raise_for_status(response, "/auth/token")
        return response.json()

    def complete_onboarding(self) -> None:
        for path, body in (
            ("/api/onboarding/core_config", None),
            ("/api/onboarding/analytics", None),
            (
                "/api/onboarding/integration",
                {"client_id": self.settings.client_id, "redirect_uri": self.settings.redirect_uri},
            ),
        ):
            response = self.request("POST", path, json_body=body)
            if response.status_code == 403:
                # Already done on a previous attempt.
                continue
            self._raise_for_status(response, path)

    def get_config(self) -> dict[str, Any]:
        return self.get_json("/api/config")

    def list_config_entries(self, domain: str | None = None) -> list[dict[str, Any]]:
        params = {"domain": domain} if domain else None
        return self.get_json("/api/config/config_entries/entry", params=params)

    def start_config_flow(self, handler: str) -> dict[str, Any]:
        return self.post_json("/api/config/config_entries/flow", {"handler": handler})

    def submit_config_flow(self, flow_id: str, data: dict[str, Any]) -> dict[str, Any]:
        return self.post_json(f"/api/config/config_entries/flow/{flow_id}", data)

    def reload_config_entry(self, entry_id: str) -> None:
        response = self.request("POST", f"/api/config/config_entries/entry/{entry_id}/reload")
        self._raise_for_status(response, f"reload {entry_id}")

    def delete_config_entry(self, entry_id: str) -> None:
        response = self.request("DELETE", f"/api/config/config_entries/entry/{entry_id}")
        self._raise_for_status(response, f"delete {entry_id}")

    def call_service(self, domain: str, service: str, data: dict[str, Any]) -> Any:
        return self.post_json(f"/api/services/{domain}/{service}", data)

    def get_state(self, entity_id: str) -> dict[str, Any] | None:
        response = self.request("GET", f"/api/states/{entity_id}")
        if response.status_code == 404:
            return None
        self._raise_for_status(response, f"/api/states/{entity_id}")
        return response.json()


class HaWsClient:
    """Small synchronous Home Assistant websocket client for setup commands."""

    def __init__(self, settings: HaE2ESettings, token: str) -> None:
        self._ws = sync_connect(settings.ws_url, max_size=None, open_timeout=10, proxy=None)
        hello = json.loads(self._ws.recv(timeout=10))
        if hello.get("type") != "auth_required":
            self._ws.close()
            raise HaApiError(f"unexpected websocket greeting: {hello}")
        self._ws.send(json.dumps({"type": "auth", "access_token": token}))
        auth = json.loads(self._ws.recv(timeout=10))
        if auth.get("type") != "auth_ok":
            self._ws.close()
            raise HaApiError(f"websocket authentication failed: {auth}")
        self._next_id = 1

    def close(self) -> None:
        self._ws.close()

    def command(self, command_type: str, **kwargs: Any) -> Any:
        command_id = self._next_id
        self._next_id += 1
        self._ws.send(json.dumps({"id": command_id, "type": command_type, **kwargs}))
        while True:
            raw = self._ws.recv(timeout=60)
            if isinstance(raw, bytes):
                continue
            message = json.loads(raw)
            if message.get("id") != command_id:
                continue
            if message.get("type") == "result":
                if not message.get("success", True):
                    raise HaApiError(f"{command_type} failed: {message}")
                return message.get("result")
            if message.get("type") == "error":
                raise HaApiError(f"{command_type} failed: {message.get('error')}")


def _onboarding_step_done(status: list[dict[str, Any]], step: str) -> bool:
    return any(entry.get("step") == step and entry.get("done") for entry in status)


def ensure_session(settings: HaE2ESettings) -> HaSession:
    """Onboard Home Assistant on first use, or reuse the harness refresh token."""

    rest = HaRestClient(settings)
    try:
        rest.wait_until_up()
        status = rest.onboarding_status()
        credentials_path = settings.credentials_path
        if _onboarding_step_done(status, "user"):
            if not credentials_path.exists():
                raise HarnessConfigError(
                    "Home Assistant is already onboarded but the harness credentials are missing. "
                    f"Reset Home Assistant with: {RESET_COMMAND}"
                )
            credentials = _read_credentials(credentials_path)
            try:
                tokens = rest.refresh_access_token(credentials.refresh_token)
            except HaApiError as exc:
                raise HarnessConfigError(
                    f"could not refresh the harness login: {exc}. Reset Home Assistant with: {RESET_COMMAND}"
                ) from exc
            credentials = HarnessCredentials(
                username=credentials.username,
                password=credentials.password,
                client_id=credentials.client_id,
                refresh_token=tokens.get("refresh_token", credentials.refresh_token),
            )
            _write_credentials(credentials_path, credentials)
            rest.token = tokens["access_token"]
            rest.wait_running()
            rest.complete_onboarding()
            return HaSession(access_token=rest.token, credentials=credentials)

        username = f"ha-e2e-{secrets.token_hex(3)}"
        password = secrets.token_urlsafe(24)
        auth_code = rest.create_onboarding_user(username, password)
        tokens = rest.exchange_code(auth_code)
        credentials = HarnessCredentials(
            username=username,
            password=password,
            client_id=settings.client_id,
            refresh_token=tokens["refresh_token"],
        )
        # Persist before finishing onboarding so a failure can be resumed.
        _write_credentials(credentials_path, credentials)
        rest.token = tokens["access_token"]
        rest.wait_running()
        rest.complete_onboarding()
        final_status = rest.onboarding_status()
        missing = [step["step"] for step in final_status if not step.get("done")]
        if missing:
            raise HarnessConfigError(f"onboarding did not complete; pending steps: {missing}")
        return HaSession(access_token=rest.token, credentials=credentials)
    finally:
        rest.close()


def _wait_for_entry(rest: HaRestClient, entry_id: str, timeout: float = ENTRY_TIMEOUT_SECONDS) -> None:
    deadline = time.monotonic() + timeout
    last_state = "missing"
    while time.monotonic() < deadline:
        entries = rest.list_config_entries()
        entry = next((item for item in entries if item.get("entry_id") == entry_id), None)
        if entry is not None:
            last_state = str(entry.get("state"))
            if last_state == "loaded":
                return
            if last_state in ("setup_error", "setup_retry", "migration_error"):
                reason = entry.get("reason") or entry.get("error_reason") or ""
                raise HarnessConfigError(f"config entry {entry_id} is {last_state}: {reason}")
        time.sleep(0.5)
    raise HarnessConfigError(f"config entry {entry_id} did not load within {timeout}s (state={last_state})")


def _create_entry_via_flow(
    rest: HaRestClient,
    handler: str,
    data: dict[str, Any],
    *,
    attempts: int = 20,
) -> dict[str, Any]:
    last_result: dict[str, Any] | None = None
    for attempt in range(attempts):
        result = rest.start_config_flow(handler)
        if result.get("type") == "create_entry":
            return result
        if result.get("type") == "abort":
            raise HarnessConfigError(f"{handler} flow aborted: {result.get('reason')}")
        if result.get("type") != "form":
            raise HarnessConfigError(f"unexpected {handler} flow result: {result}")

        flow_id = result["flow_id"]
        result = rest.submit_config_flow(flow_id, data)
        last_result = result
        if result.get("type") == "create_entry":
            return result
        if result.get("type") == "abort":
            raise HarnessConfigError(f"{handler} flow aborted: {result.get('reason')}")
        if result.get("type") == "form":
            errors = result.get("errors") or {}
            if any(str(error) in ("cannot_connect", "unknown") for error in errors.values()):
                time.sleep(min(1.0 + attempt * 0.5, 5.0))
                continue
            raise HarnessConfigError(f"{handler} flow rejected the input: {errors}")
        raise HarnessConfigError(f"unexpected {handler} flow result: {result}")
    raise HarnessConfigError(f"{handler} flow did not create an entry after {attempts} attempts: {last_result}")


def _entry_id_from_result(rest: HaRestClient, result: dict[str, Any], domain: str) -> str:
    entry = result.get("result")
    if isinstance(entry, dict) and entry.get("entry_id"):
        return str(entry["entry_id"])
    if result.get("entry_id"):
        return str(result["entry_id"])
    latest = rest.list_config_entries(domain)
    if not latest:
        raise HarnessConfigError(f"config flow created no {domain} entry")
    return str(latest[-1]["entry_id"])


def _reload_or_recreate(rest: HaRestClient, entry: dict[str, Any]) -> str:
    entry_id = str(entry["entry_id"])
    try:
        rest.reload_config_entry(entry_id)
    except HaApiError:
        rest.delete_config_entry(entry_id)
        time.sleep(1.0)
        raise
    _wait_for_entry(rest, entry_id)
    return entry_id


def ensure_wyoming_entry(
    rest: HaRestClient,
    settings: HaE2ESettings,
    host: str,
    state: dict[str, str],
) -> str:
    """Reuse or create a Wyoming config entry for ``host``.

    The config-entry API omits ``data`` (host/port), so the harness persists the
    entry IDs it created under tests/ha_e2e/.state and reuses them by ID.
    """

    key = _wyoming_entry_key(settings, host)
    entries = rest.list_config_entries("wyoming")
    tracked_id = state.get(key)
    if tracked_id:
        existing = next((entry for entry in entries if entry.get("entry_id") == tracked_id), None)
        if existing is not None:
            try:
                entry_id = _reload_or_recreate(rest, existing)
                state[key] = entry_id
                _save_entry_state(settings, state)
                return entry_id
            except HaApiError as exc:
                _LOGGER.warning("Reloading Wyoming entry %s failed; recreating it: %s", tracked_id, exc)

    result = _create_entry_via_flow(
        rest,
        "wyoming",
        {"host": host, "port": settings.wyoming_port},
    )
    entry_id = _entry_id_from_result(rest, result, "wyoming")
    _wait_for_entry(rest, entry_id)
    state[key] = entry_id
    _save_entry_state(settings, state)
    return entry_id


def ensure_custom_entry(rest: HaRestClient, settings: HaE2ESettings, state: dict[str, str]) -> str:
    """Reuse or create the test-only conversation agent entry."""

    key = "custom:ha_e2e_scripted"
    entries = rest.list_config_entries("ha_e2e_scripted")
    tracked_id = state.get(key)
    existing = next((entry for entry in entries if entry.get("entry_id") == tracked_id), None)
    if existing is None and entries:
        existing = entries[0]
    if existing is not None:
        try:
            entry_id = _reload_or_recreate(rest, existing)
            state[key] = entry_id
            _save_entry_state(settings, state)
            return entry_id
        except HaApiError as exc:
            _LOGGER.warning("Reloading the HA E2E scripted entry failed; recreating it: %s", exc)

    result = _create_entry_via_flow(rest, "ha_e2e_scripted", {})
    entry_id = _entry_id_from_result(rest, result, "ha_e2e_scripted")
    _wait_for_entry(rest, entry_id)
    state[key] = entry_id
    _save_entry_state(settings, state)
    return entry_id


def _wait_for_entities(
    rest: HaRestClient,
    ws: HaWsClient,
    entry_id: str,
    domains: tuple[str, ...],
    timeout: float = ENTITY_TIMEOUT_SECONDS,
) -> dict[str, str]:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        registry = ws.command("config/entity_registry/list")
        found: dict[str, str] = {}
        for entry in registry:
            if entry.get("config_entry_id") != entry_id or entry.get("disabled_by") is not None:
                continue
            entity_id = str(entry.get("entity_id", ""))
            domain = entity_id.split(".", 1)[0]
            if domain in domains and domain not in found:
                found[domain] = entity_id
        if all(domain in found for domain in domains):
            states_ready = True
            for entity_id in found.values():
                state = rest.get_state(entity_id)
                if state is None or state.get("state") == "unavailable":
                    states_ready = False
                    break
            if states_ready:
                return {domain: found[domain] for domain in domains}
        time.sleep(0.5)
    raise HarnessConfigError(f"entities {domains} for config entry {entry_id} did not become ready")


def _first_voice(ws: HaWsClient, tts_entity_id: str) -> str:
    result = ws.command("tts/engine/voices", engine_id=tts_entity_id, language="en")
    voices = (result or {}).get("voices") or []
    if not voices:
        raise HarnessConfigError(f"TTS engine {tts_entity_id} advertised no English voices")
    return str(voices[0]["voice_id"])


def _ensure_pipeline(ws: HaWsClient, name: str, fields: dict[str, Any]) -> str:
    listing = ws.command("assist_pipeline/pipeline/list")
    for pipeline in (listing or {}).get("pipelines", []):
        if pipeline.get("name") != name:
            continue
        try:
            ws.command("assist_pipeline/pipeline/delete", pipeline_id=pipeline["id"])
        except HaApiError as exc:
            raise HarnessConfigError(f"could not delete old pipeline {name}: {exc}") from exc
    result = ws.command(
        "assist_pipeline/pipeline/create",
        name=name,
        language="en",
        conversation_language="en",
        wake_word_entity=None,
        wake_word_id=None,
        **fields,
    )
    if not isinstance(result, dict) or not result.get("id"):
        raise HarnessConfigError(f"pipeline creation returned an unexpected result: {result}")
    return str(result["id"])


def configure_ha(settings: HaE2ESettings, session: HaSession) -> HaStack:
    """Add config entries and pipelines, and return the ready stack."""

    rest = HaRestClient(settings, session.access_token)
    ws = HaWsClient(settings, session.access_token)
    try:
        rest.wait_running()
        entry_state = _load_entry_state(settings)
        _reset_untracked_wyoming_entries(rest, settings, entry_state)
        custom_entry_id = ensure_custom_entry(rest, settings, entry_state)
        good_entry_id = ensure_wyoming_entry(rest, settings, settings.wyoming_host, entry_state)
        bad_entry_id = ensure_wyoming_entry(rest, settings, settings.bad_stt_host, entry_state)

        custom_entities = _wait_for_entities(rest, ws, custom_entry_id, ("conversation",))
        good_entities = _wait_for_entities(rest, ws, good_entry_id, ("stt", "tts"))
        bad_entities = _wait_for_entities(rest, ws, bad_entry_id, ("stt",))
        voice = _first_voice(ws, good_entities["tts"])

        good_pipeline_id = _ensure_pipeline(
            ws,
            "HA E2E",
            {
                "conversation_engine": custom_entities["conversation"],
                "stt_engine": good_entities["stt"],
                "stt_language": "en",
                "tts_engine": good_entities["tts"],
                "tts_language": "en",
                "tts_voice": voice,
            },
        )
        bad_pipeline_id = _ensure_pipeline(
            ws,
            "HA E2E Bad STT",
            {
                "conversation_engine": custom_entities["conversation"],
                "stt_engine": bad_entities["stt"],
                "stt_language": "en",
                "tts_engine": None,
                "tts_language": None,
                "tts_voice": None,
            },
        )
        ha_version = str(rest.get_config().get("version", "unknown"))
    finally:
        ws.close()

    _LOGGER.info(
        "Home Assistant %s ready: good pipeline=%s, bad STT pipeline=%s, voice=%s",
        ha_version,
        good_pipeline_id,
        bad_pipeline_id,
        voice,
    )
    return HaStack(
        settings=settings,
        session=session,
        rest=rest,
        good=PipelineInfo(
            id=good_pipeline_id,
            stt_entity_id=good_entities["stt"],
            tts_entity_id=good_entities["tts"],
            voice=voice,
        ),
        bad_stt=PipelineInfo(
            id=bad_pipeline_id,
            stt_entity_id=bad_entities["stt"],
            tts_entity_id=None,
            voice=None,
        ),
        conversation_engine=custom_entities["conversation"],
        conversation_id=f"ha-e2e-{secrets.token_hex(8)}",
        ha_version=ha_version,
    )
